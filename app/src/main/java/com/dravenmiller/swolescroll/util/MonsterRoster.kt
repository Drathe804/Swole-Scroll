    // 1. Generates the 12-Monster Lineup for the Siege Banner
    fun getHordeLineup(muscleGroup: String): List<Int> {
        val muscle = muscleGroup.lowercase()

        // Pick the faction based on muscle
        val faction = when {
            muscle.contains("chest") || muscle.contains("triceps") -> allMonsters // Replace with your chestMonsters list later!
            muscle.contains("legs") || muscle.contains("glutes") -> allMonsters // Replace with legMonsters later!
            else -> allMonsters
        }

        // We use a "seeded" shuffle based on the muscle group's name.
        // This guarantees that "Chest" will always generate the exact same 12 monsters today,
        // so they don't change every time you type a number!
        val stableRandom = kotlin.random.Random(muscleGroup.hashCode())
        return faction.shuffled(stableRandom).take(12)
    }

    // We now use the exercise's position in the list (index) instead of its name!
    fun getMonsterFromHorde(muscleGroup: String, exerciseIndex: Int, isPhoenix: Boolean = false): Int {
        // 🦅 The Phoenix Exception
        if (isPhoenix) return R.drawable.monster_phoenix // Replace with your actual Phoenix image ID

        val horde = getHordeLineup(muscleGroup)
        if (horde.isEmpty()) return R.drawable.ic_launcher_foreground

        // By using the exact index, monster #0 is always different from monster #1, #2, etc.
        val safeIndex = exerciseIndex % horde.size
        return horde[safeIndex]
    }

